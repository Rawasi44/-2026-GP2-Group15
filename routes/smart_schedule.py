"""Smart Schedule pages.

The system generates personalized event suggestions based on the user's
availability and recommendation profile. Suggested events are not saved
automatically. The user chooses which individual events to save to their
Personal Calendar.
"""

from datetime import date, timedelta

from flask import (
    Blueprint,
    flash,
    redirect,
    render_template,
    request,
    session,
    url_for,
)
from flask_login import current_user, login_required

from extensions import db
from models.calendar_event import CalendarEvent
from models.event import Event
from services.scheduling_service import (
    MAX_HORIZON_DAYS,
    TIME_WINDOWS,
    generate_smart_schedule,
    validate_planning_request,
)


smart_schedule_bp = Blueprint("smart_schedule", __name__)


def build_schedule(
    selected,
    preferred,
    max_per_day,
    today,
):
    """
    Validate the user's planning request and generate a Smart Schedule.

    max_per_day can be:
    - an integer such as 1, 2, or 3
    - None when the user selects "Any"
    """
    days, validated_count = validate_planning_request(
        selected,
        preferred,
        max_per_day,
        today=today,
    )

    schedule = generate_smart_schedule(
        current_user.user_id,
        days,
        preferred_time=preferred,
        max_per_day=validated_count,
    )

    return days, validated_count, schedule


def store_proposed_schedule(schedule):
    """
    Store only the event/date pairs generated by the server.

    This allows the save endpoint to verify that the user is saving
    an event that actually appeared in the generated Smart Schedule.
    """
    proposed = [
        {
            "event_id": item["event_id"],
            "date": item["date"].isoformat(),
        }
        for day in schedule
        for item in day["items"]
    ]

    session["afaq_proposed_schedule"] = {
        "user_id": current_user.user_id,
        "items": proposed,
    }

    return proposed


@smart_schedule_bp.route(
    "/smart-schedule",
    methods=["GET", "POST"],
)
@login_required
def planner_page():
    schedule = None
    selected = []
    preferred = "any"
    max_per_day = "2"

    today = date.today()

    # ---------------------------------------------------------
    # Generate a new Smart Schedule
    # ---------------------------------------------------------
    if request.method == "POST":
        selected = request.form.getlist("dates")
        preferred = request.form.get(
            "preferred_time",
            "any",
        )

        max_per_day = request.form.get(
            "max_per_day",
            "2",
        )

        try:
            (
                days,
                validated_count,
                schedule,
            ) = build_schedule(
                selected,
                preferred,
                max_per_day,
                today,
            )

        except ValueError as exc:
            session.pop(
                "afaq_proposed_schedule",
                None,
            )
            session.pop(
                "afaq_last_schedule_request",
                None,
            )

            flash(
                str(exc),
                "warning",
            )

        else:
            # Keep the user's last planning request so the generated
            # suggestions can be shown again after saving one event.
            session["afaq_last_schedule_request"] = {
                "dates": [
                    day.isoformat()
                    for day in days
                ],
                "preferred_time": preferred,
                "max_per_day": (
                    "any"
                    if validated_count is None
                    else str(validated_count)
                ),
            }

            max_per_day = (
                "any"
                if validated_count is None
                else str(validated_count)
            )

            proposed = store_proposed_schedule(
                schedule
            )

            if not proposed:
                flash(
                    "No matching events were found for the selected dates and time preference. "
                    "Try other dates or choose 'Any time'.",
                    "warning",
                )

    # ---------------------------------------------------------
    # Restore the most recently generated suggestions
    # after the user saves an individual event.
    # ---------------------------------------------------------
    elif request.args.get("restore") == "1":
        last_request = session.get(
            "afaq_last_schedule_request"
        )

        if last_request:
            selected = last_request.get(
                "dates",
                [],
            )

            preferred = last_request.get(
                "preferred_time",
                "any",
            )

            max_per_day = last_request.get(
                "max_per_day",
                "2",
            )

            try:
                (
                    days,
                    validated_count,
                    schedule,
                ) = build_schedule(
                    selected,
                    preferred,
                    max_per_day,
                    today,
                )

            except ValueError:
                schedule = None

            else:
                max_per_day = (
                    "any"
                    if validated_count is None
                    else str(validated_count)
                )

                store_proposed_schedule(
                    schedule
                )

    return render_template(
        "smart_schedule.html",
        schedule=schedule,
        selected_dates=selected,
        preferred_time=preferred,
        max_per_day=max_per_day,
        time_windows=TIME_WINDOWS,
        today=today,
        last_day=(
            today
            + timedelta(
                days=MAX_HORIZON_DAYS
            )
        ),

        # This is no longer a 7-day limit.
        # It only represents the maximum possible number of
        # unique dates within the allowed planning horizon.
        max_days=MAX_HORIZON_DAYS,
    )


@smart_schedule_bp.route(
    "/smart-schedule/save",
    methods=["POST"],
)
@login_required
def save_schedule():
    """
    Save ONE event selected by the user.

    Generating a Smart Schedule never automatically saves all
    suggestions to the Personal Calendar.
    """

    proposed = session.get(
        "afaq_proposed_schedule"
    )

    if (
        not proposed
        or proposed.get("user_id")
        != current_user.user_id
    ):
        flash(
            "Generate a Smart Schedule before saving an event.",
            "warning",
        )

        return redirect(
            url_for(
                "smart_schedule.planner_page"
            )
        )

    # The individual event chosen by the user.
    try:
        event_id = int(
            request.form.get(
                "event_id",
                ""
            )
        )

        planned_day = date.fromisoformat(
            request.form.get(
                "planned_date",
                ""
            )
        )

    except (TypeError, ValueError):
        flash(
            "Invalid event or date.",
            "warning",
        )

        return redirect(
            url_for(
                "smart_schedule.planner_page",
                restore=1,
            )
        )

    # ---------------------------------------------------------
    # Security check:
    # only allow event/date pairs that were actually generated
    # by the server in the user's latest Smart Schedule.
    # ---------------------------------------------------------
    proposed_pairs = {
        (
            int(item["event_id"]),
            item["date"],
        )
        for item in proposed.get(
            "items",
            []
        )
        if (
            "event_id" in item
            and "date" in item
        )
    }

    requested_pair = (
        event_id,
        planned_day.isoformat(),
    )

    if requested_pair not in proposed_pairs:
        flash(
            "This event is not part of your generated Smart Schedule.",
            "warning",
        )

        return redirect(
            url_for(
                "smart_schedule.planner_page",
                restore=1,
            )
        )

    today = date.today()

    # The planned date must still be inside the allowed horizon.
    if not (
        today
        <= planned_day
        <= today
        + timedelta(
            days=MAX_HORIZON_DAYS
        )
    ):
        flash(
            "The selected date is no longer valid.",
            "warning",
        )

        return redirect(
            url_for(
                "smart_schedule.planner_page",
                restore=1,
            )
        )

    event = db.session.get(
        Event,
        event_id,
    )

    if not event or not event.is_active:
        flash(
            "This event is no longer available.",
            "warning",
        )

        return redirect(
            url_for(
                "smart_schedule.planner_page",
                restore=1,
            )
        )

    # Make sure the event is actually available on that day.
    event_end = (
        event.end_date
        or event.start_date
    )

    if not (
        event.start_date
        <= planned_day
        <= event_end
    ):
        flash(
            "This event is not available on the selected date.",
            "warning",
        )

        return redirect(
            url_for(
                "smart_schedule.planner_page",
                restore=1,
            )
        )

    # Do not duplicate the same event in the user's calendar.
    existing = CalendarEvent.query.filter_by(
        user_id=current_user.user_id,
        event_id=event_id,
    ).first()

    if existing:
        flash(
            "This event is already in your Personal Calendar.",
            "warning",
        )

        return redirect(
            url_for(
                "smart_schedule.planner_page",
                restore=1,
            )
        )

    calendar_entry = CalendarEvent(
        user_id=current_user.user_id,
        event_id=event_id,
        scheduled_date=planned_day,
    )

    db.session.add(
        calendar_entry
    )
    db.session.commit()

    flash(
        f'"{event.title}" was saved to your Personal Calendar.',
        "success",
    )

    # Return to the same generated suggestions instead of
    # clearing the whole Smart Schedule.
    return redirect(
        url_for(
            "smart_schedule.planner_page",
            restore=1,
        )
    )